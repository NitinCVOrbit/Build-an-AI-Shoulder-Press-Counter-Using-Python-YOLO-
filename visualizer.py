import cv2


# ============================================================
# DRAW ANGLE
# ============================================================

def draw_angle(frame, point, angle):

    x, y = int(point[0]), int(point[1])

    cv2.putText(
        frame,
        f"{int(angle)}",
        (x + 10, y - 10),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.7,
        (0, 255, 255),
        2
    )


# ============================================================
# DRAW INFORMATION PANEL
# ============================================================

def draw_info_panel(
    frame,
    counter,
    state,
    average_angle
):

    # --------------------------------------------------------
    # PANEL
    # --------------------------------------------------------

    cv2.rectangle(
        frame,
        (10, 10),
        (370, 160),
        (20, 20, 20),
        -1
    )


    # --------------------------------------------------------
    # TITLE
    # --------------------------------------------------------

    cv2.putText(
        frame,
        "SHOULDER PRESS",
        (25, 45),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.9,
        (0, 255, 255),
        2
    )


    # --------------------------------------------------------
    # REPS
    # --------------------------------------------------------

    cv2.putText(
        frame,
        f"REPS: {counter}",
        (25, 85),
        cv2.FONT_HERSHEY_SIMPLEX,
        1.0,
        (0, 255, 0),
        3
    )


    # --------------------------------------------------------
    # STATE
    # --------------------------------------------------------

    cv2.putText(
        frame,
        f"STATE: {state}",
        (25, 120),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.8,
        (255, 255, 255),
        2
    )


    # --------------------------------------------------------
    # ANGLE
    # --------------------------------------------------------

    cv2.putText(
        frame,
        f"ANGLE: {int(average_angle)}",
        (210, 120),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.7,
        (255, 255, 0),
        2
    )


    return frame